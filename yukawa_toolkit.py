def test_yukawa_zero_limit() -> None:
    """
    Comprueba que la corrección Yukawa al perihelio tiende a cero
    cuando alpha -> 0.
    """
    a = 0.387 * AU   # semieje mayor de Mercurio
    e = 0.2056
    M = M_SUN
    params = YukawaParams(alpha=0.0, lambda_m=1.0 * AU)
    DeltaY = perihelion_precession_yukawa(a, e, M, params)
    tol = 1e-12  # rad
    print(f"[test_yukawa_zero_limit] |DeltaY| = {abs(DeltaY):.3e} rad")
    assert abs(DeltaY) < tol


def test_light_deflection_GR_limit() -> None:
    """
    Comprueba que se recupera la deflexión GR (~1%) cuando alpha->0 y
    gamma_inf=1.
    """
    b = R_SUN
    M = M_SUN
    params = YukawaParams(alpha=0.0, lambda_m=1.0 * AU)
    alpha_tot, alpha_gr = deflection_angle_yukawa(b, M, params, gamma_inf=1.0)
    rel_err = abs(alpha_tot - alpha_gr) / abs(alpha_gr)
    print(f"[test_light_deflection_GR_limit] relative error = {rel_err:.3e}")
    assert rel_err < 1e-2


def test_quad_error_estimate() -> None:
    """
    Test de control: integra una gaussiana y comprueba la precisión
    relativa de quad.
    """
    def f(x):
        return np.exp(-x**2)

    res, _ = quad(f, -10.0, 10.0, epsabs=0.0, epsrel=1e-8)
    true_val = np.sqrt(np.pi)
    rel_err = abs(res - true_val) / true_val
    print(f"[test_quad_error_estimate] relative error = {rel_err:.3e}")
    assert rel_err < 1e-6


def run_all_tests() -> None:
    print("Running validation tests...")
    test_yukawa_zero_limit()
    test_light_deflection_GR_limit()
    test_quad_error_estimate()
    print("All tests passed.")


